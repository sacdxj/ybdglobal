def main():
    wb = load_workbook(WORKBOOK)
    ws = wb["05_口播文案库"]
    for row_idx in range(2, ws.max_row + 1):
        if ws.cell(row_idx, 1).value != "第6周":
            continue
        category = ws.cell(row_idx, 3).value
        if category not in UPDATES:
            continue
        topic, script, scene = UPDATES[category]
        ws.cell(row_idx, 2).value = topic
        ws.cell(row_idx, 4).value = script
        ws.cell(row_idx, 5).value = scene
        ws.row_dimensions[row_idx].height = 170 if category == "实时行业热点新闻" else 145

    ws4 = wb["04_未来4周主题安排"]
    for row_idx in range(2, ws4.max_row + 1):
        if ws4.cell(row_idx, 1).value == "第6周":
            ws4.cell(row_idx, 5).value = "跨境贸易风险与踩坑：平台佣金调整后，为什么要重算利润？"
            ws4.cell(row_idx, 6).value = "案例与商务合作 vlog：平台限制自发货后，卖家最该提前看什么？"
            break

    wb.save(WORKBOOK)
    print(WORKBOOK)


