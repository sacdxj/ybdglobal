def main():
    wb = load_workbook(WORKBOOK)
    ws = wb["05_口播文案库"]

    for row_idx in range(2, ws.max_row + 1):
        if ws.cell(row_idx, 1).value != "第5周":
            continue
        category = ws.cell(row_idx, 3).value
        if category not in OPTIMIZED:
            continue
        topic, script, scene = OPTIMIZED[category]
        ws.cell(row_idx, 2).value = topic
        ws.cell(row_idx, 4).value = script
        ws.cell(row_idx, 5).value = scene
        ws.row_dimensions[row_idx].height = 170 if category == "实时行业热点新闻" else 145

    wb.save(WORKBOOK)
    print(WORKBOOK)


if __name__ == "__main__":
    main()
